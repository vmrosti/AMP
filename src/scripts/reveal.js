// Jednotný scroll-reveal pro prvky s třídou .reveal — přidá .is-visible při vstupu
// do viewportu. Respektuje prefers-reduced-motion (viz CSS pravidlo v global.css,
// které u reduced motion rovnou vypíná transition/opacity).
if ("IntersectionObserver" in window) {
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          io.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.15, rootMargin: "0px 0px -40px 0px" }
  );
  document.querySelectorAll(".reveal").forEach((el) => io.observe(el));
} else {
  document.querySelectorAll(".reveal").forEach((el) => el.classList.add("is-visible"));
}
